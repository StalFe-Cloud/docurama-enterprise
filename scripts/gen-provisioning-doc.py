#!/usr/bin/env python3
"""Generate DOCURAMA-DNS-EMAIL-PROVISIONING.md from the live provisioning API data."""
import json

d = json.load(open("/tmp/prov-data.json"))
c = d["company"]

KIND_LABEL = {
    "MAILBOX_SMTP": "Real mailbox (SMTP credentials)",
    "MAILBOX": "Real mailbox (or forwarder)",
    "SHARED_INBOX": "Real mailbox / shared inbox",
    "ALIAS": "Alias / forwarder",
    "REPORTS": "Report destination",
}

def md_escape(s: str) -> str:
    return s.replace("|", "\\|")

lines = []
w = lines.append

w("# Docurama: DNS and Email Provisioning Guide")
w("")
w(f"**{c['legalName']}** · {c['address']}")
w("")
w(f"Domain: **docurama.eu** · Data residency: {c['dataResidency']}")
w("Generated by the platform console (Admin → Email & DNS) on 2026-09-14.")
w("")
w("This guide provisions every DNS sub-domain and email address required to operate")
w("Docurama securely, professionally and in full compliance with EU regulations")
w("(GDPR, eIDAS, RFC 5321/2142 mail standards). Placeholder values (origin IPs,")
w("mail-relay targets, SIREN/VAT numbers) are marked **to be updated**.")
w("")
w("---")
w("")
w("## 1. Company identity (fill-in placeholders)")
w("")
w("| Field | Value |")
w("|---|---|")
w(f"| Legal name | {md_escape(c['legalName'])} |")
w(f"| Registered address | {md_escape(c['address'])} |")
w(f"| Registration | {md_escape(c['registrationNumber'])} |")
w(f"| VAT number | {md_escape(c['vatNumber'])} |")
w(f"| Share capital | {md_escape(c['shareCapital'])} |")
w(f"| Phone | {md_escape(c['phone'])} |")
w(f"| DPO / privacy | {c['dpoEmail']} |")
w(f"| Legal | {c['legalEmail']} |")
w(f"| Security | {c['securityEmail']} |")
w(f"| Administration | {c['adminEmail']} |")
w("")
w("## 2. DNS sub-domains on docurama.eu")
w("")
w("| Host | Purpose | Record | Target | Audience |")
w("|---|---|---|---|---|")
for s in d["subdomains"]:
    w(f"| `{s['fqdn']}` | {md_escape(s['purpose'])} | {s['recordType']} | `{md_escape(s['target'])}` | {s['audience']} |")
w("")
w("All production hosts use Let's Encrypt (ACME) certificates; `staging` uses the")
w("Let's Encrypt staging CA during pre-production verification.")
w("")
w("## 3. Email addresses (12) — by function")
w("")
cats = []
for e in d["emails"]:
    if e["category"] not in cats:
        cats.append(e["category"])
for cat in cats:
    w(f"### {cat}")
    w("")
    w("| Address | Display name | Type | Purpose | Forwards to | Standard / Priority |")
    w("|---|---|---|---|---|---|")
    for e in [x for x in d["emails"] if x["category"] == cat]:
        fwd = f"`{e['forwardsTo']}`" if e.get("forwardsTo") else "—"
        std = e.get("rfc", "—")
        w(f"| `{e['address']}` | {md_escape(e['displayName'])} | {KIND_LABEL[e['kind']]} | {md_escape(e['purpose'])} | {fwd} | {md_escape(std)} · {e['priority']} |")
    w("")
w("### Sender identity (deliverability tip)")
w("")
w("When sending via Docurama, configure the sender as:")
w("")
w("```")
w("Docurama Sign <notifications@docurama.eu>")
w("```")
w("")
w("The branded display name materially improves open rates on signing invitations")
w("and is already configured in Platform Settings → SMTP.")
w("")
w("## 4. DNS records for deliverability & trust")
w("")
w("| Group | Name | Type | Value | Purpose |")
w("|---|---|---|---|---|")
for r in d["dnsRecords"]:
    w(f"| {r['group']} | `{r['name']}` | {r['type']} | `{md_escape(r['value'])}` | {md_escape(r['purpose'])} |")
w("")
w("### MTA-STS policy file")
w("")
w("Serve the following at `https://mta-sts.docurama.eu/.well-known/mta-sts.txt`:")
w("")
w("```")
w("version: STSv1")
w("mode: enforce")
w("mx: mail.docurama.eu")
w("max_age: 604800")
w("```")
w("")
w("### security.txt (RFC 9116)")
w("")
w("Serve at `https://docurama.eu/.well-known/security.txt`:")
w("")
w("```")
w("Contact: mailto:security@docurama.eu")
w("Expires: 2027-12-31T23:00:00.000Z")
w("Preferred-Languages: en, fr")
w("Canonical: https://docurama.eu/.well-known/security.txt")
w("```")
w("")
w("## 5. Setup order (runbook)")
w("")
w("1. **Zone baseline** — publish the A/CNAME hosts (section 2) at the registrar;")
w("   the full BIND zone is attached as `docurama.eu.zone`.")
w("2. **Mailbox P0s first** — create `notifications@`, `admin@` (or the forwarder to")
w("   docurama@voiria.com), `postmaster@`, `abuse@`, `privacy@`, `security@`.")
w("3. **Relay & SPF/DKIM** — connect the EU relay, publish SPF + both DKIM selectors,")
w("   then keep DMARC at `p=quarantine` until alignment reports are clean (watch")
w("   `dmarc@docurama.eu`), then move to `p=reject`.")
w("4. **PTR/rDNS** — set `51.75.124.20 → mail.docurama.eu` at the hosting provider so")
w("   the SMTP HELO matches; mismatched PTR is the fastest route to spam folders.")
w("5. **MTA-STS + TLS-RPT** — publish the TXT records and the policy file over HTTPS.")
w("6. **CAA** — restrict certificate issuance to Let's Encrypt with iodef reporting.")
w("7. **Business aliases** — `support@`, `sales@`, `billing@`, `contact@`, `legal@`.")
w("8. **Registry data** — replace SIREN, VAT, share capital and phone placeholders")
w("   from the company Kbis; they flow into the legal footer, invoices and DSAR responses.")
w("")
w("## 6. Compliance notes (GDPR / eIDAS)")
w("")
w("- `privacy@docurama.eu` is the DSAR intake required for GDPR Arts. 13/14/30")
w("  transparency and one-month response duties; DSAR cases are tracked in the")
w("  admin console under Legal & DSAR.")
w("- The audit chain, retention policies and legal holds in the platform satisfy")
w("  eIDAS evidence requirements for advanced electronic signatures (AdES/PAdES).")
w("- EU data residency: all sub-domains terminate on EU-West origins; no")
w("  sub-processor outside the EEA is involved in the signing pipeline.")
w("")

with open("/home/z/my-project/download/DOCURAMA-DNS-EMAIL-PROVISIONING.md", "w") as f:
    f.write("\n".join(lines))

print("doc written:", len(lines), "lines")
